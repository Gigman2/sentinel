// Package seed creates the demo tenant (organization, admin, project,
// components, integrations and mappings). It is idempotent and is also used
// by tests to build fixtures.
package seed

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/Gigman2/sentinel/backend/api/internal/auth"
	"github.com/Gigman2/sentinel/backend/api/internal/domain"
)

// Config names the tenant to seed. Empty tokens are generated on first run
// and left unchanged on later runs; supplied tokens always replace the stored hash.
type Config struct {
	OrgSlug      string
	OrgName      string
	AdminEmail   string
	AdminToken   string
	MonitorToken string
	DeployToken  string
}

// Result holds the seeded IDs. Token fields contain plaintext only when the
// token was generated by this call; otherwise they are empty.
type Result struct {
	OrgID                string
	ProjectID            string
	AdminToken           string
	MonitorIntegrationID string
	MonitorToken         string
	DeployIntegrationID  string
	DeployToken          string
	Components           map[string]string // component slug → id
}

const environment = "production"

type mapping struct{ external, component string }

// Seed creates or reconciles the demo tenant in a single transaction.
func Seed(ctx context.Context, pool *pgxpool.Pool, cfg Config) (Result, error) {
	if cfg.OrgSlug == "" || cfg.OrgName == "" || cfg.AdminEmail == "" {
		return Result{}, errors.New("seed: OrgSlug, OrgName and AdminEmail are required")
	}
	tx, err := pool.Begin(ctx)
	if err != nil {
		return Result{}, err
	}
	defer tx.Rollback(ctx)

	res := Result{Components: map[string]string{}}

	if err := tx.QueryRow(ctx, `
		INSERT INTO organizations (slug, name) VALUES ($1, $2)
		ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name
		RETURNING id::text`, cfg.OrgSlug, cfg.OrgName).Scan(&res.OrgID); err != nil {
		return Result{}, fmt.Errorf("seed organization: %w", err)
	}

	if res.AdminToken, err = seedAdmin(ctx, tx, res.OrgID, cfg); err != nil {
		return Result{}, err
	}

	if err := tx.QueryRow(ctx, `
		INSERT INTO projects (organization_id, slug, name) VALUES ($1, 'uppsel-production', 'Uppsel Production')
		ON CONFLICT (organization_id, slug) DO UPDATE SET name = EXCLUDED.name
		RETURNING id::text`, res.OrgID).Scan(&res.ProjectID); err != nil {
		return Result{}, fmt.Errorf("seed project: %w", err)
	}

	for slug, name := range map[string]string{"checkout-api": "Checkout API", "payment-service": "Payment Service"} {
		var id string
		if err := tx.QueryRow(ctx, `
			INSERT INTO components (organization_id, project_id, environment, slug, display_name)
			VALUES ($1, $2, $3, $4, $5)
			ON CONFLICT (project_id, environment, slug) DO UPDATE SET display_name = EXCLUDED.display_name
			RETURNING id::text`, res.OrgID, res.ProjectID, environment, slug, name).Scan(&id); err != nil {
			return Result{}, fmt.Errorf("seed component %s: %w", slug, err)
		}
		res.Components[slug] = id
	}

	if res.MonitorIntegrationID, res.MonitorToken, err = seedIntegration(ctx, tx, res, "monitor", domain.CapabilityIncidentInput, cfg.MonitorToken,
		[]mapping{{"checkout-prod", "checkout-api"}, {"payments-prod", "payment-service"}}); err != nil {
		return Result{}, err
	}
	if res.DeployIntegrationID, res.DeployToken, err = seedIntegration(ctx, tx, res, "deploys", domain.CapabilityChangeSource, cfg.DeployToken,
		[]mapping{{"payment-service", "payment-service"}}); err != nil {
		return Result{}, err
	}

	if err := tx.Commit(ctx); err != nil {
		return Result{}, err
	}
	return res, nil
}

func seedAdmin(ctx context.Context, tx pgx.Tx, orgID string, cfg Config) (generated string, err error) {
	var userID string
	if err := tx.QueryRow(ctx, `
		INSERT INTO users (email, display_name) VALUES ($1, 'Admin')
		ON CONFLICT (email) DO UPDATE SET email = EXCLUDED.email
		RETURNING id::text`, cfg.AdminEmail).Scan(&userID); err != nil {
		return "", fmt.Errorf("seed admin user: %w", err)
	}
	if _, err := tx.Exec(ctx, `
		INSERT INTO memberships (organization_id, user_id, role) VALUES ($1, $2, $3)
		ON CONFLICT (organization_id, user_id) DO UPDATE SET role = EXCLUDED.role`,
		orgID, userID, domain.RoleAdmin); err != nil {
		return "", fmt.Errorf("seed admin membership: %w", err)
	}

	if cfg.AdminToken != "" {
		if _, err := tx.Exec(ctx, `
			INSERT INTO api_tokens (user_id, token_hash) VALUES ($1, $2)
			ON CONFLICT (token_hash) DO UPDATE SET revoked_at = NULL
			WHERE api_tokens.user_id = EXCLUDED.user_id`, userID, auth.Hash(cfg.AdminToken)); err != nil {
			return "", fmt.Errorf("seed admin token: %w", err)
		}
		return "", nil
	}

	var hasToken bool
	if err := tx.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM api_tokens WHERE user_id = $1 AND revoked_at IS NULL)`, userID).Scan(&hasToken); err != nil {
		return "", err
	}
	if hasToken {
		return "", nil
	}
	plain, hash := auth.NewToken(domain.UserTokenPrefix)
	if _, err := tx.Exec(ctx, `INSERT INTO api_tokens (user_id, token_hash) VALUES ($1, $2)`, userID, hash); err != nil {
		return "", fmt.Errorf("seed admin token: %w", err)
	}
	return plain, nil
}

func seedIntegration(ctx context.Context, tx pgx.Tx, res Result, name, capability, token string, mappings []mapping) (id, generated string, err error) {
	err = tx.QueryRow(ctx, `SELECT id::text FROM integrations WHERE project_id = $1 AND name = $2 ORDER BY created_at LIMIT 1`,
		res.ProjectID, name).Scan(&id)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		hash := auth.Hash(token)
		if token == "" {
			generated, hash = auth.NewToken(domain.IntegrationTokenPrefix)
		}
		if err := tx.QueryRow(ctx, `
			INSERT INTO integrations (organization_id, project_id, name, capability, credential_hash)
			VALUES ($1, $2, $3, $4, $5) RETURNING id::text`,
			res.OrgID, res.ProjectID, name, capability, hash).Scan(&id); err != nil {
			return "", "", fmt.Errorf("seed integration %s: %w", name, err)
		}
	case err != nil:
		return "", "", fmt.Errorf("find integration %s: %w", name, err)
	default:
		if _, err := tx.Exec(ctx, `UPDATE integrations SET capability = $2, enabled = true WHERE id = $1`, id, capability); err != nil {
			return "", "", fmt.Errorf("reconcile integration %s: %w", name, err)
		}
		if token != "" {
			if _, err := tx.Exec(ctx, `UPDATE integrations SET credential_hash = $2 WHERE id = $1`, id, auth.Hash(token)); err != nil {
				return "", "", fmt.Errorf("update %s credential: %w", name, err)
			}
		}
	}

	for _, m := range mappings {
		if _, err := tx.Exec(ctx, `
			INSERT INTO integration_component_mappings (integration_id, external_component_id, environment, component_id)
			VALUES ($1, $2, $3, $4)
			ON CONFLICT (integration_id, external_component_id, environment) DO UPDATE SET component_id = EXCLUDED.component_id`,
			id, m.external, environment, res.Components[m.component]); err != nil {
			return "", "", fmt.Errorf("seed mapping %s: %w", m.external, err)
		}
	}
	return id, generated, nil
}
