// Command sentinel-api runs Sentinel's API and its maintenance subcommands.
package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"github.com/Gigman2/sentinel/backend/api/internal/platform/database"
	"github.com/Gigman2/sentinel/backend/api/internal/server"
	"github.com/Gigman2/sentinel/backend/api/internal/support/seed"
)

const usage = `usage: sentinel-api <command>

commands:
  migrate      apply pending database migrations (reads DATABASE_URL)
  seed         create or reconcile the demo tenant (reads DATABASE_URL, SEED_* variables)
  serve        run the HTTP API (reads DATABASE_URL, HOST, PORT; default port 8080 on all interfaces)
  healthcheck  exit 0 if the local API answers /healthz (reads PORT; for container healthchecks)`

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	var err error
	switch os.Args[1] {
	case "migrate":
		err = runMigrate(ctx)
	case "seed":
		err = runSeed(ctx)
	case "serve":
		err = runServe(ctx)
	case "healthcheck":
		err = runHealthcheck(ctx)
	default:
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func databaseURL() (string, error) {
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		return "", errors.New("DATABASE_URL is not set")
	}
	return dsn, nil
}

func runMigrate(ctx context.Context) error {
	dsn, err := databaseURL()
	if err != nil {
		return err
	}
	results, err := database.MigrateWithResults(ctx, dsn)
	if err != nil {
		return err
	}
	if len(results) == 0 {
		fmt.Println("no pending migrations")
		return nil
	}
	for _, r := range results {
		fmt.Printf("applied %s (%s)\n", r.Source.Path, r.Duration)
	}
	return nil
}

func getenv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// listenAddr is HOST:PORT. An empty HOST listens on all interfaces; PORT
// defaults to 8080.
func listenAddr() string {
	return net.JoinHostPort(os.Getenv("HOST"), getenv("PORT", "8080"))
}

// healthURL is the API's /healthz on the loopback interface, at PORT.
func healthURL() string {
	return "http://" + net.JoinHostPort("127.0.0.1", getenv("PORT", "8080")) + "/healthz"
}

func runSeed(ctx context.Context) error {
	dsn, err := databaseURL()
	if err != nil {
		return err
	}
	pool, err := database.Open(ctx, dsn)
	if err != nil {
		return err
	}
	defer pool.Close()

	res, err := seed.Seed(ctx, pool, seed.Config{
		OrgSlug:      getenv("SEED_ORG_SLUG", "uppsel"),
		OrgName:      getenv("SEED_ORG_NAME", "Uppsel"),
		AdminEmail:   getenv("SEED_ADMIN_EMAIL", "admin@uppsel.test"),
		AdminToken:   os.Getenv("SEED_ADMIN_TOKEN"),
		MonitorToken: os.Getenv("SEED_MONITOR_TOKEN"),
		DeployToken:  os.Getenv("SEED_DEPLOY_TOKEN"),
	})
	if err != nil {
		return err
	}
	fmt.Printf("organization   %s\nproject        %s\nmonitor        %s\ndeploys        %s\n",
		res.OrgID, res.ProjectID, res.MonitorIntegrationID, res.DeployIntegrationID)
	// Only tokens generated by this run are printed, once. Supplied tokens never are.
	for _, t := range []struct{ label, value string }{
		{"admin token  ", res.AdminToken},
		{"monitor token", res.MonitorToken},
		{"deploy token ", res.DeployToken},
	} {
		if t.value != "" {
			fmt.Printf("%s  %s  (shown once; store it now)\n", t.label, t.value)
		}
	}
	return nil
}

func runServe(ctx context.Context) error {
	logger := slog.New(slog.NewJSONHandler(os.Stdout, nil))
	dsn, err := databaseURL()
	if err != nil {
		return err
	}
	pool, err := database.Open(ctx, dsn)
	if err != nil {
		return err
	}
	defer pool.Close()

	srv := &http.Server{
		Addr:              listenAddr(),
		Handler:           server.New(server.Deps{Pool: pool, Logger: logger, Now: time.Now}),
		ReadHeaderTimeout: 10 * time.Second,
		ReadTimeout:       30 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       120 * time.Second,
	}

	serveErr := make(chan error, 1)
	go func() {
		logger.Info("listening", "addr", srv.Addr)
		serveErr <- srv.ListenAndServe()
	}()

	select {
	case err := <-serveErr:
		// The listener failed (e.g. port in use); nothing is in flight.
		return err
	case <-ctx.Done():
	}

	// Stop accepting new requests and wait for in-flight ones before the
	// deferred pool.Close runs.
	logger.Info("shutting down")
	shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := srv.Shutdown(shutdownCtx); err != nil {
		return fmt.Errorf("graceful shutdown: %w", err)
	}
	if err := <-serveErr; !errors.Is(err, http.ErrServerClosed) {
		return err
	}
	return nil
}

func runHealthcheck(ctx context.Context) error {
	ctx, cancel := context.WithTimeout(ctx, 3*time.Second)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, healthURL(), nil)
	if err != nil {
		return err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("healthz returned %d", resp.StatusCode)
	}
	return nil
}
